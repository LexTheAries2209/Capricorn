#!/bin/sh
# Build PR #639 as an isolated, manually authorized tool, leaving smartctl 7.5 intact.
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
SOURCE_ROOT="$REPO_ROOT/ThirdParty/SmartctlUSBRaw"
WORK_ROOT=$(mktemp -d /private/tmp/capricorn-usbraw-build.XXXXXX)
ARCHITECTURES=${CAPRICORN_USBRAW_ARCHITECTURES:-"arm64 x86_64"}
tar -xzf "$SOURCE_ROOT/smartmontools-c68a1b9.tar.gz" -C "$WORK_ROOT"
cd "$WORK_ROOT/smartmontools-usbraw"
patch -p1 < "$SOURCE_ROOT/capricorn-manual.patch"
cp "$SOURCE_ROOT/dist-version.sh" util/dist-version.sh
./autogen.sh
SOURCE_DIR="$PWD"
# A source snapshot has no upstream ancestry for the generated drive-db revision.
# The executable still embeds the pinned revision from dist-version.sh.
export SMARTMONTOOLS_TEST_BUILD=1
BINARIES=""
for architecture in $ARCHITECTURES; do
    BUILD_DIR="$WORK_ROOT/$architecture"
    mkdir -p "$BUILD_DIR"
    cd "$BUILD_DIR"
    CFLAGS="-arch $architecture -mmacosx-version-min=14.0" \
    CXXFLAGS="-arch $architecture -mmacosx-version-min=14.0" \
    OBJCXXFLAGS="-arch $architecture -mmacosx-version-min=14.0" \
    LDFLAGS="-arch $architecture -mmacosx-version-min=14.0" \
        "$SOURCE_DIR/configure" --disable-shared --disable-dependency-tracking \
        --with-drivedbdir=no --with-update-smart-drivedb=no
    make -C include -j"$(sysctl -n hw.ncpu)"
    make -C lib -j"$(sysctl -n hw.ncpu)" libsmartmon.la
    make -C src -j"$(sysctl -n hw.ncpu)" smartctl
    BINARIES="$BINARIES $BUILD_DIR/src/smartctl"
done
DESTINATION="$REPO_ROOT/Capricorn/Resources/Smartmontools"
mkdir -p "$DESTINATION"
# Build paths are generated by mktemp and contain no whitespace.
lipo -create $BINARIES -output "$DESTINATION/smartctl-usbraw"
codesign --force --sign - "$DESTINATION/smartctl-usbraw"
echo "Built $DESTINATION/smartctl-usbraw"
